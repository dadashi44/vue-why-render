/**
 * Build the WASM engine and inline it as a base64 module.
 *
 * 1. Runs wasm-pack to compile Rust → WASM
 * 2. Reads the .wasm binary
 * 3. Generates src/wasm/inline.ts with the bytes as base64
 *
 * The inline module is imported by src/core/wasm.ts and passed to initSync(),
 * making the WASM self-contained within the JS bundle — no external fetch needed.
 */
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const crateDir = resolve(root, 'crates/wasm-engine')
const pkgDir = resolve(root, 'src/wasm/pkg')
const inlineFile = resolve(root, 'src/wasm/inline.ts')

// Step 1: Build with wasm-pack
console.log('wasm: compiling Rust to WASM...')
execSync('wasm-pack build --target web --release --out-dir ../../src/wasm/pkg', {
    cwd: crateDir,
    stdio: 'inherit',
})

// Step 2: Read .wasm binary
const wasmPath = resolve(pkgDir, 'vue_why_render_wasm_bg.wasm')
if (!existsSync(wasmPath)) {
    throw new Error(`wasm: ${wasmPath} not found`)
}

const wasmBytes = readFileSync(wasmPath)
const base64 = wasmBytes.toString('base64')
const sizeKb = (wasmBytes.length / 1024).toFixed(1)

// Step 3: Generate inline module
const output = `// Auto-generated by scripts/build-wasm.mjs — do not edit.
// WASM engine: ${sizeKb} KB

const WASM_BASE64 = '${base64}'

let _bytes: Uint8Array | null = null

export function getWasmBytes(): Uint8Array {
    if (!_bytes) {
        const raw = atob(WASM_BASE64)
        _bytes = new Uint8Array(raw.length)
        for (let i = 0; i < raw.length; i++) _bytes[i] = raw.charCodeAt(i)
    }
    return _bytes
}
`

writeFileSync(inlineFile, output)
console.log(`wasm: inline module generated (${sizeKb} KB)`)
